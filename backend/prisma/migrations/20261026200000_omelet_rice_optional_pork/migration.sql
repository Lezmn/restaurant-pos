-- ข้าวไข่เจียว: "หมูสับ" เป็นท็อปปิ้ง ไม่บังคับ (เดิมอยู่กลุ่มเนื้อสัตว์ = ลูกค้าต้องเลือก 1 อย่างก่อนสั่ง)
-- แก้เฉพาะตัวเลือกชื่อ "หมูสับ" ของเมนูชื่อ "ข้าวไข่เจียว" — ไม่มีเมนูนี้ / ร้านเปลี่ยนชื่อไปแล้ว = ไม่มีอะไรเปลี่ยน
UPDATE "menu_options"
SET "group" = 'EXTRA'
WHERE "name" = 'หมูสับ'
  AND "group" = 'PROTEIN'
  AND "menuItemId" IN (SELECT "id" FROM "menu_items" WHERE "name" = 'ข้าวไข่เจียว');
